#!/usr/bin/env python3
"""Generate PlantUML views of the Note Management ontology.

Reads docs/ontology/ont-note.ttl and writes two diagrams next to it:

  ont-note-class.puml   every concept and relationship, with cardinalities
  ont-note-state.puml   the status lifecycle

The ontology owns the content. The diagrams are views and are never edited by hand.

Conventions the script relies on:
  - A relationship whose domain and range are the same class is a lifecycle
    relationship. It is drawn in the state diagram, not the class diagram.
  - Cardinalities come from the SHACL property shapes (sh:minCount / sh:maxCount).
  - A ":rule" annotation links an element or constraint to the rule it enforces.
  - ":isInitial true" marks the status a new Note has.

Usage:
  uv run --with rdflib tools/ontology_to_puml.py            write the diagrams
  uv run --with rdflib tools/ontology_to_puml.py --check    fail if they are out of date
"""

import argparse
import sys
from pathlib import Path

from rdflib import OWL, RDF, RDFS, BNode, Graph, Literal, Namespace
from rdflib.collection import Collection
from rdflib.namespace import SH, XSD

ROOT = Path(__file__).resolve().parent.parent
ONTOLOGY = ROOT / "docs" / "ontology" / "ont-note.ttl"
OUT_DIR = ROOT / "docs" / "ontology"
THEME = "../architecture/theme.puml"

# Datatype properties that describe the lifecycle and are drawn in the state diagram.
LIFECYCLE_ATTRIBUTES = {"isInitial"}

DATATYPES = {XSD.string: "string", XSD.boolean: "boolean", XSD.integer: "integer"}


class Ontology:
    def __init__(self, path: Path):
        self.g = Graph().parse(path, format="turtle")
        self.ns = Namespace(str(dict(self.g.namespaces())[""]))
        self.artifact_id = self.ns["artifactId"]
        self.rule = self.ns["rule"]

    def local(self, node) -> str:
        return str(node).removeprefix(str(self.ns))

    def label(self, node) -> str:
        return str(self.g.value(node, RDFS.label) or self.local(node))

    def aid(self, node) -> str:
        return str(self.g.value(node, self.artifact_id) or "")

    def rule_ids(self, node) -> list[str]:
        return sorted(self.aid(r) for r in self.g.objects(node, self.rule))

    def classes(self) -> list:
        found = [c for c in self.g.subjects(RDF.type, OWL.Class) if not isinstance(c, BNode)]
        return sorted(found, key=self.aid)

    def members(self, cls) -> list:
        """Members of an enumeration class, in the order the ontology lists them."""
        for equivalent in self.g.objects(cls, OWL.equivalentClass):
            one_of = self.g.value(equivalent, OWL.oneOf)
            if one_of is not None:
                return list(Collection(self.g, one_of))
        return []

    def object_properties(self) -> list:
        return sorted(self.g.subjects(RDF.type, OWL.ObjectProperty), key=self.aid)

    def cardinality(self, domain, prop) -> tuple[int | None, int | None, list[str]]:
        for shape in self.g.subjects(SH.targetClass, domain):
            for constraint in self.g.objects(shape, SH.property):
                if self.g.value(constraint, SH.path) == prop:
                    low = self.g.value(constraint, SH.minCount)
                    high = self.g.value(constraint, SH.maxCount)
                    return (
                        int(low) if low is not None else None,
                        int(high) if high is not None else None,
                        self.rule_ids(constraint),
                    )
        return None, None, []


def multiplicity(low: int | None, high: int | None) -> str:
    low_text = "0" if low is None else str(low)
    high_text = "*" if high is None else str(high)
    return low_text if low_text == high_text else f"{low_text}..{high_text}"


def header(source: Path, name: str, title: str) -> list[str]:
    rel = source.relative_to(ROOT)
    return [
        f"@startuml {name}",
        f"!include {THEME}",
        f"title {title}",
        "",
        f"' GENERATED by tools/ontology_to_puml.py from {rel}. Do not edit.",
        "",
    ]


def class_diagram(onto: Ontology) -> str:
    lines = header(ONTOLOGY, "ont-note-class", "Note Management - Concepts and Relationships")
    classes = onto.classes()
    lifecycle = {
        p for p in onto.object_properties()
        if onto.g.value(p, RDFS.domain) == onto.g.value(p, RDFS.range)
    }

    datatype_properties = [
        p for p in onto.g.subjects(RDF.type, OWL.DatatypeProperty)
        if onto.local(p) not in LIFECYCLE_ATTRIBUTES
    ]

    for cls in classes:
        name = onto.local(cls)
        stereotypes = [onto.aid(cls)]
        members = onto.members(cls)
        if members:
            stereotypes.insert(0, "Enum")
        tag = " ".join(f"<<{s}>>" for s in stereotypes)
        body = [f"    {onto.label(m)}" for m in members]
        for prop in sorted(datatype_properties, key=onto.local):
            if cls in set(onto.g.objects(prop, RDFS.domain)):
                datatype = DATATYPES.get(onto.g.value(prop, RDFS.range), "string")
                body.append(f"    + {onto.local(prop)}: {datatype}")
        declaration = f'class "{onto.label(cls)}" as {name} {tag}'
        lines += [declaration + " {", *body, "}"] if body else [declaration]
    lines.append("")

    for child in classes:
        for parent in onto.g.objects(child, RDFS.subClassOf):
            if parent in classes:
                lines.append(f"{onto.local(parent)} <|-- {onto.local(child)}")

    for prop in onto.object_properties():
        if prop in lifecycle:
            continue
        domain = onto.g.value(prop, RDFS.domain)
        target = onto.g.value(prop, RDFS.range)
        low, high, rules = onto.cardinality(domain, prop)
        label = "\\n".join([onto.local(prop), onto.aid(prop), *rules])
        lines.append(
            f'{onto.local(domain)} --> "{multiplicity(low, high)}" {onto.local(target)} : {label}'
        )

    lines += ["", "@enduml", ""]
    return "\n".join(lines)


def state_diagram(onto: Ontology) -> str:
    lifecycle = [
        p for p in onto.object_properties()
        if onto.g.value(p, RDFS.domain) == onto.g.value(p, RDFS.range)
    ]
    if not lifecycle:
        return ""
    prop = lifecycle[0]
    status_class = onto.g.value(prop, RDFS.domain)
    statuses = onto.members(status_class)
    initial = [
        s for s in statuses
        if onto.g.value(s, onto.ns["isInitial"]) == Literal(True)
    ]
    transitions = [(s, t) for s in statuses for t in onto.g.objects(s, prop)]

    lines = header(ONTOLOGY, "ont-note-state", "Note Management - Status Lifecycle")
    lines += [
        "skinparam state {",
        "  BackgroundColor #FFFFFF",
        "  BorderColor #475569",
        "  FontColor #0F172A",
        "  StartColor #475569",
        "  EndColor #475569",
        "}",
        "",
    ]
    for status in statuses:
        lines.append(f'state "{onto.label(status)}" as {onto.local(status)}')
    lines.append("")
    for status in initial:
        rules = ", ".join(onto.rule_ids(status))
        lines.append(f"[*] --> {onto.local(status)}" + (f" : {rules}" if rules else ""))
    rules = ", ".join(onto.rule_ids(prop))
    for source, target in transitions:
        lines.append(
            f"{onto.local(source)} --> {onto.local(target)}" + (f" : {rules}" if rules else "")
        )
    for status in statuses:
        if not list(onto.g.objects(status, prop)):
            lines.append(f"{onto.local(status)} --> [*]")
    lines += ["", "@enduml", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the diagrams are out of date")
    args = parser.parse_args()

    onto = Ontology(ONTOLOGY)
    outputs = {
        OUT_DIR / "ont-note-class.puml": class_diagram(onto),
        OUT_DIR / "ont-note-state.puml": state_diagram(onto),
    }

    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        print("out of date, regenerate with tools/ontology_to_puml.py:")
        for path in stale:
            print(f"  {path}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
